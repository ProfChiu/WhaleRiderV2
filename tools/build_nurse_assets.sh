#!/bin/bash
# Copies the chosen NURSE images into assets/nurse (resized), then embeds them
# as base64 in src/nurse_assets.js so index.html runs straight from disk
# (no local server needed). Re-run after swapping any image.
# Requires the NURSE folder to be "Available offline" in Dropbox.
set -e
HERE="$(cd "$(dirname "$0")/.." && pwd)"
SRC="$HERE/../../_ASSETS/Characters/NURSE"
OUT="$HERE/assets/nurse"
mkdir -p "$OUT"

# key  =  source file
MAP="nurseStand=sprites/nurse-dancing-stand.png
nurseWalk=sprites/nurse-rain-walking-profile.png
nurseSpin=sprites/nurse-dancing-spin.png
nurseBow=sprites/nurse-dancing-bow.png
faceSmile=faces/smile-a.png
faceUpset=faces/upset-a.png
faceHappy=faces/happy-a.png
faceSmirk=faces/smirk-a.png
faceSleepy=faces/sleepy-a.png"

FINAL="$HERE/src/nurse_assets.js"
JS="$FINAL.tmp"
echo "// Generated by tools/build_nurse_assets.sh. Do not edit by hand." > "$JS"
echo "window.NURSE_IMG = {" >> "$JS"
while IFS='=' read -r key file; do
  cp "$SRC/$file" "$OUT/$key.png"
  case "$key" in face*) MAX=160 ;; *) MAX=440 ;; esac
  sips -Z "$MAX" "$OUT/$key.png" >/dev/null
  printf '  %s: "data:image/png;base64,%s",\n' "$key" "$(base64 -i "$OUT/$key.png" | tr -d '\n')" >> "$JS"
  echo "embedded $key <- $file"
done <<< "$MAP"
echo "};" >> "$JS"
mv "$JS" "$FINAL"   # swap in only when every image succeeded
