#!/usr/bin/env python3
"""Freeze the live game (game/) as a playable snapshot in versions/vX.Y/.

  python3 tools/bump_version.py 0.1 "Ten GAME 220 questions" "What changed, one or two sentences."
  python3 tools/bump_version.py --manifest      # only rebuild versions/manifest.js

The snapshot is a full copy of game/, so it never changes when the live game does.
Its version.js is stamped with the number and a link back to the launcher, and
versions/manifest.js (read by the root index.html picker) is rebuilt from every
versions/v*/version.json. The live game in game/ is never modified.
"""
import datetime, json, re, shutil, subprocess, sys
from pathlib import Path

ROOT = Path(__file__).resolve().parent.parent
LIVE = ROOT / 'game'
VERS = ROOT / 'versions'


def vkey(name):
    return tuple(int(n) for n in name.lstrip('v').split('.'))


def build_manifest():
    rows = []
    for d in VERS.glob('v*'):
        meta = d / 'version.json'
        if d.is_dir() and meta.exists():
            rows.append(json.loads(meta.read_text()))
    rows.sort(key=lambda r: vkey(r['version']), reverse=True)   # newest first
    out = VERS / 'manifest.js'
    out.write_text('// Generated by tools/bump_version.py. Do not edit by hand.\n'
                   'window.VERSIONS = ' + json.dumps(rows, indent=2, ensure_ascii=False) + ';\n')
    print(f'Manifest:  versions/manifest.js  ({len(rows)} version(s): '
          + ', '.join('v' + r['version'] for r in rows) + ')')


def bump(version, title, summary):
    if not re.fullmatch(r'\d+\.\d+', version):
        sys.exit(f'Version must look like 0.1, got {version!r}')
    dest = VERS / f'v{version}'
    if dest.exists():
        sys.exit(f'{dest.relative_to(ROOT)} already exists. Snapshots are never overwritten.')
    VERS.mkdir(exist_ok=True)
    shutil.copytree(LIVE, dest, ignore=shutil.ignore_patterns('.DS_Store', '*.tmp'))
    (dest / 'version.js').write_text(
        '// Frozen snapshot. Do not edit; change game/ and bump a new version instead.\n'
        f"window.APP_VERSION = '{version}';\n"
        "window.APP_LAUNCHER = '../../index.html';\n")
    try:
        commit = subprocess.run(['git', 'rev-parse', '--short', 'HEAD'], cwd=ROOT,
                                capture_output=True, text=True).stdout.strip()
    except OSError:
        commit = ''
    meta = {'version': version, 'title': title, 'summary': summary,
            'date': datetime.date.today().isoformat(), 'commit': commit,
            'path': f'versions/v{version}/index.html'}
    (dest / 'version.json').write_text(json.dumps(meta, indent=2, ensure_ascii=False) + '\n')
    print(f'Archived:  game/  →  versions/v{version}/')
    print(f'Open:      versions/v{version}/index.html  (or pick it in index.html)')
    build_manifest()


if __name__ == '__main__':
    a = sys.argv[1:]
    if a == ['--manifest']:
        build_manifest()
    elif len(a) == 3:
        bump(*a)
    else:
        sys.exit(__doc__)
