#!/usr/bin/env python3
"""Embed final art from game/art/ into game/src/art_assets.js.

Drop a PNG (or JPG) into game/art/ named after the texture it replaces, e.g.
game/art/tower.png, then run:

    python3 tools/build_art.py

The game loads embedded art first and draws stand-ins only for what is missing, so
art can arrive one piece at a time. Embedding (base64) lets index.html run straight
from disk with no local server. See game/art/README.md for the texture names.
"""
import base64, os
from pathlib import Path

ROOT = Path(__file__).resolve().parent.parent
ART = ROOT / 'game' / 'art'
OUT = ROOT / 'game' / 'src' / 'art_assets.js'
MIME = {'.png': 'image/png', '.jpg': 'image/jpeg', '.jpeg': 'image/jpeg', '.webp': 'image/webp'}

rows = []
for f in sorted(ART.iterdir()) if ART.exists() else []:
    mime = MIME.get(f.suffix.lower())
    if not mime:
        continue
    data = base64.b64encode(f.read_bytes()).decode()
    rows.append(f'  {f.stem}: "data:{mime};base64,{data}",')
    print(f'embedded {f.stem:<12} <- game/art/{f.name}  ({f.stat().st_size // 1024} KB)')

tmp = OUT.with_suffix('.js.tmp')
tmp.write_text('// Generated by tools/build_art.py from game/art/. Do not edit by hand.\n'
               'window.ART_IMG = {\n' + '\n'.join(rows) + ('\n' if rows else '') + '};\n')
os.replace(tmp, OUT)   # swap in only when complete
print(f'wrote {OUT.relative_to(ROOT)} ({len(rows)} image(s))')
